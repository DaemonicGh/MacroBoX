#include <math.h>
#include "modules/types/veclc_s_vec3.h"

t_vec3i	vec3_round(t_vec3 p)
{
	return ((t_vec3i){
		.x = round(p.x),
		.y = round(p.y),
		.z = round(p.z),
	});
}
