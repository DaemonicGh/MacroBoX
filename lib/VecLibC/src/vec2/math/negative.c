#include "modules/types/veclc_s_vec2.h"

t_vec2	vec2_neg(t_vec2 p)
{
	return ((t_vec2){
		.x = -p.x,
		.y = -p.y,
	});
}

t_vec2i	vec2i_neg(t_vec2i p)
{
	return ((t_vec2i){
		.x = -p.x,
		.y = -p.y,
	});
}
